// Command update-alpine refreshes the Alpine Linux base image pin in
// internal/image/alpine_pin.go from the release metadata Alpine publishes
// for each architecture. Run via `go generate ./internal/image/`.
package main

import (
	"bufio"
	"flag"
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"runtime"
	"strings"
)

var arches = []string{"x86_64", "aarch64"}

type release struct {
	Branch  string
	Version string
	SHA256  string
}

func main() {
	branch := flag.String("branch", "latest-stable", "Alpine branch to pin, e.g. v3.24 (default: latest stable)")
	flag.Parse()

	releases := map[string]release{}
	for _, arch := range arches {
		url := fmt.Sprintf("https://dl-cdn.alpinelinux.org/alpine/%s/releases/%s/latest-releases.yaml", *branch, arch)
		r, err := fetchMinirootfs(url)
		if err != nil {
			fatal("%s: %v", arch, err)
		}
		releases[arch] = r
	}

	first := releases[arches[0]]
	for _, arch := range arches[1:] {
		if r := releases[arch]; r.Version != first.Version || r.Branch != first.Branch {
			fatal("architectures disagree on the current release: %s has %s (%s), %s has %s (%s); retry later",
				arches[0], first.Version, first.Branch, arch, r.Version, r.Branch)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by tools/update-alpine; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package image\n\n")
	fmt.Fprintf(&b, "const (\n")
	fmt.Fprintf(&b, "\talpineBranch  = %q\n", first.Branch)
	fmt.Fprintf(&b, "\talpineVersion = %q\n", first.Version)
	fmt.Fprintf(&b, ")\n\n")
	fmt.Fprintf(&b, "// alpineRootfsSHA256 is keyed by Alpine's architecture name.\n")
	fmt.Fprintf(&b, "var alpineRootfsSHA256 = map[string]string{\n")
	for _, arch := range arches {
		fmt.Fprintf(&b, "\t%q: %q,\n", arch, releases[arch].SHA256)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		fatal("format generated source: %v", err)
	}
	_, self, _, _ := runtime.Caller(0)
	out := filepath.Join(filepath.Dir(self), "..", "..", "internal", "image", "alpine_pin.go")
	if err := os.WriteFile(out, src, 0o644); err != nil {
		fatal("write %s: %v", out, err)
	}
	fmt.Printf("pinned Alpine %s (%s)\n", first.Version, first.Branch)
}

// fetchMinirootfs pulls the alpine-minirootfs entry out of a
// latest-releases.yaml. The file is a flat list of flavors with scalar
// fields, so a line scanner is enough.
func fetchMinirootfs(url string) (release, error) {
	resp, err := http.Get(url)
	if err != nil {
		return release{}, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return release{}, fmt.Errorf("%s: %s", url, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return release{}, err
	}

	var cur release
	var flavor string
	flush := func() (release, bool) {
		if flavor == "alpine-minirootfs" && cur.Version != "" && cur.SHA256 != "" && cur.Branch != "" {
			return cur, true
		}
		return release{}, false
	}

	sc := bufio.NewScanner(strings.NewReader(string(body)))
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "-") {
			if r, ok := flush(); ok {
				return r, nil
			}
			cur, flavor = release{}, ""
			line = strings.TrimPrefix(line, "-")
		}
		key, val, ok := strings.Cut(strings.TrimSpace(line), ":")
		if !ok {
			continue
		}
		val = strings.TrimSpace(val)
		switch key {
		case "flavor":
			flavor = val
		case "branch":
			cur.Branch = val
		case "version":
			cur.Version = val
		case "sha256":
			cur.SHA256 = val
		}
	}
	if r, ok := flush(); ok {
		return r, nil
	}
	return release{}, fmt.Errorf("no alpine-minirootfs entry in %s", url)
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "update-alpine: "+format+"\n", args...)
	os.Exit(1)
}
